"""Register supplied raster sheets without redrawing their artwork.

Extract connected silhouettes, normalize authored trunk core widths and anchors,
pack lossless transparent runtime atlases. Sources remain unchanged.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.ndimage import label,binary_dilation
ROOT=Path(__file__).resolve().parents[1];SRC=ROOT/'Chaua-Educa-main/assets/v7-source';OUT=ROOT/'Chaua-Educa-main/assets/v7';OUT.mkdir(exist_ok=True)
def extract(name,count):
 a=np.array(Image.open((SRC/name).with_suffix('.webp')).convert('RGBA'));labs,n=label(a[:,:,3]>100);counts=np.bincount(labs.ravel());counts[0]=0
 ids=sorted(counts.argsort()[-count:],key=lambda k:(np.where(labs==k)[0].mean()//(a.shape[0]/(4 if count==16 else 2)),np.where(labs==k)[1].mean()))
 result=[]
 for k in ids:
  yy,xx=np.where(labs==k);x0=max(0,xx.min()-4);y0=max(0,yy.min()-4);x1=min(a.shape[1],xx.max()+5);y1=min(a.shape[0],yy.max()+5)
  crop=a[y0:y1,x0:x1].copy();mask=binary_dilation(labs[y0:y1,x0:x1]==k,iterations=3);crop[:,:,3]=np.where(mask&(crop[:,:,3]>8),crop[:,:,3],0);crop[crop[:,:,3]==0,:3]=0
  result.append(Image.fromarray(crop))
 return result
meta={}
for name in ['lower','upper']:
 frames=extract('trees-'+name+'.png',4);atlas=Image.new('RGBA',(1024,1024));entries=[]
 for i,im in enumerate(frames):
  a=np.array(im);row=int(im.height*.93 if name=='lower' else im.height*.08);xs=np.where(a[row,:,3]>150)[0];left,right=int(xs.min()),int(xs.max()+1);core=right-left;scale=240/core
  # All main trunks have identical width; decorations keep their authored ratio.
  scale=min(scale,240/((left+right)/2),240/(im.width-(left+right)/2),460/im.height);sz=(round(im.width*scale),round(im.height*scale));im=im.resize(sz,Image.Resampling.LANCZOS)
  anchorX=(left+right)/2*scale;dx=round(256-anchorX);dy=20
  assert dx>=8 and dx+sz[0]<504 and sz[1]+dy<504
  atlas.alpha_composite(im,((i%2)*512+dx,(i//2)*512+dy));entries.append({'rect':[(i%2)*512,(i//2)*512,512,512],'content':[dx,dy,*sz],'core':[left*scale+dx,right*scale+dx],'anchor':[256,dy if name=='lower' else dy+sz[1]],'endY':dy+sz[1],'spliceY':dy+round(sz[1]*(.93 if name=='lower' else .08))})

  if name=='lower' and i==3:
   pixels=np.array(im);column=40;rgb=pixels[:,column,:];hits=np.where((rgb[:,3]>180)&(rgb[:,0]>rgb[:,1]*1.2)&(rgb[:,0]>rgb[:,2]*1.5))[0]
   entries[-1]['perch']=[dx+column,dy+int(hits[0])+2]
 atlas.save(OUT/('trees-'+name+'.webp'),lossless=True,method=6);meta[name]=entries
(OUT/'manifest.json').write_text(json.dumps(meta,indent=2)+'\n');(ROOT/'Chaua-Educa-main/js/forest-art-data.mjs').write_text('// Generated by scripts/prepare_forest_v7.py\nexport const FOREST_ART='+json.dumps(meta,separators=(',',':'))+';\n')
for p in OUT.glob('*.webp'):print(p.name,p.stat().st_size)
