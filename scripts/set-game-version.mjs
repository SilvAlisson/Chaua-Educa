import {readFileSync,writeFileSync} from 'node:fs';
const version=process.argv[2];
if(!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[1-9]\d*)?$/.test(version??''))
 throw new Error('Informe a versão no formato 1.0.1');
const revision=process.argv[3]||version;
if(revision!==version&&(!revision.startsWith(version+'-')||!/^[0-9a-z.-]+$/.test(revision)))
 throw new Error('A revisão de interface deve começar pela versão do pacote.');
const root=new URL('../',import.meta.url);
for(const file of ['package.json','package-lock.json']){
 const path=new URL(file,root),data=JSON.parse(readFileSync(path,'utf8'));
 data.version=version;
 if(file==='package-lock.json')data.packages[''].version=version;
 writeFileSync(path,JSON.stringify(data,null,2)+'\n');
}
writeFileSync(new URL('Chaua-Educa-main/js/version.mjs',root),
 `// Generated by scripts/set-game-version.mjs; keep package and runtime aligned.\nexport const GAME_VERSION='${version}';\n`);
console.log(`Versão do pacote, lockfile e jogo: ${version}`);
// One revision for the stylesheet, entry and complete browser module graph.
// Import maps preserve a single module instance for relative and absolute imports.
const {readdirSync}=await import('node:fs');
const modules=readdirSync(new URL('Chaua-Educa-main/js/',root),{recursive:true}).filter(file=>/\.(mjs|js)$/.test(file)).sort();
const imports=Object.fromEntries(modules.map(file=>[`./js/${file}`,`./js/${file}?v=${revision}`]));
const htmlPath=new URL('Chaua-Educa-main/index.html',root);
let html=readFileSync(htmlPath,'utf8').replace(/\s*<meta name="chaua-build"[^>]*>/,'').replace(/\s*<script type="importmap" id="chaua-modules">[\s\S]*?<\/script>/,'');
html=html.replace(/href="css\/style\.css(?:\?[^"\s]*)?"/,`href="css/style.css?v=${revision}"`)
 .replace(/src="js\/script\.js(?:\?[^"\s]*)?"/,`src="js/script.js?v=${revision}"`);
const map=`  <meta name="chaua-build" content="${revision}">\n  <script type="importmap" id="chaua-modules">${JSON.stringify({imports})}</script>\n`;
html=html.replace('  <script type="module"',map+'  <script type="module"');
writeFileSync(htmlPath,html);
console.log(`Interface ${revision}: CSS e ${modules.length} módulos com revisão coerente.`);
