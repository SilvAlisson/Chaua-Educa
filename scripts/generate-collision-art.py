#!/usr/bin/env python3
"""Build offline pickup masks and verify active bird body landmarks against alpha.

No runtime pixel reads. --check rejects any stale art/geometry relationship.
The inset bird cores deliberately exclude beaks, feet, wing tips and tails.
"""
from pathlib import Path
import argparse, hashlib, json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
APP=ROOT/'Chaua-Educa-main'
OUT=APP/'js/collision-art-data.mjs'
BODIES={'parrot':{'path':'public/parrot/fly/flight.webp','cell':256,'draw':160.16,'parts':[[-3,2,18,14],[32,-15,12,13]]},
        'hawk':{'path':'public/hawk/fly/flight.webp','cell':320,'draw':280,'parts':[[-12,35,31,22],[-72,13,18,12]]},
        'hawkDive':{'path':'assets/v6/hawk-atlas.webp','cell':384,'draw':299.52,'frames':[8,10,11],'parts':[[-5,15,29,21],[-66,-2,18,12]]}}

def generate():
 sources={}; bodies={}; masks={}
 for relative in ['assets/v6/chaua-atlas.webp','assets/v6/hawk-atlas.webp','assets/v7/trees-lower.webp','assets/v7/trees-upper.webp','assets/v9/tree-variants.webp']:
  sources[relative]=hashlib.sha256((APP/relative).read_bytes()).hexdigest()
 for key,info in BODIES.items():
  p=APP/info['path'];sources[info['path']]=hashlib.sha256(p.read_bytes()).hexdigest();im=Image.open(p).convert('RGBA')
  cell=info['cell'];factor=info['draw']/cell
  # Sample the interior, not only ellipse centers: all eight wing poses must
  # enclose the active core. A generous collider inside alpha is intentional.
  for f in info.get('frames',range(8)):
   alpha=im.crop((f%4*cell,f//4*cell,(f%4+1)*cell,(f//4+1)*cell)).getchannel('A')
   for dx,dy,rx,ry in info['parts']:
    samples=[(dx+x*rx,dy+y*ry) for y in [-.7,-.35,0,.35,.7] for x in [-.7,-.35,0,.35,.7] if x*x+y*y<=.7**2]
    coverage=sum(alpha.getpixel((round(cell/2+x/factor),round(cell/2+y/factor)))>=112 for x,y in samples)/len(samples)
    if coverage<.98:raise ValueError(f'{key} frame {f}: body core outside current art ({coverage:.1%})')
  bodies[key]=info['parts']
 for key,relative,count,columns,cell in [('fruit','assets/runtime/foods.webp',48,8,128),('feather','assets/v4/feather.webp',1,1,384),('shield','assets/v4/shield.webp',1,1,384)]:
  p=APP/relative;sources[relative]=hashlib.sha256(p.read_bytes()).hexdigest();im=Image.open(p).convert('RGBA');frames=[]
  for f in range(count):
   alpha=im.crop((f%columns*cell,f//columns*cell,(f%columns+1)*cell,(f//columns+1)*cell)).getchannel('A')
   # 16x16 occupancy, merged into horizontal runs. No bounding-box corners.
   spans=[]
   for row in range(16):
    start=None
    for col in range(17):
     solid=col<16 and alpha.crop((col*cell//16,row*cell//16,(col+1)*cell//16,(row+1)*cell//16)).getextrema()[1]>=112
     if solid and start is None:start=col
     if not solid and start is not None:spans.append([start,row,col-start]);start=None
   frames.append(spans)
  masks[key]=frames
 return '// Generated by scripts/generate-collision-art.py. No runtime readbacks.\nexport const COLLISION_ART='+json.dumps({'sources':sources,'bodies':bodies,'pickups':masks},separators=(',',':'))+';\n'
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args();content=generate()
 if args.check:
  if not OUT.exists() or OUT.read_text()!=content:raise SystemExit('Collision art data is stale. Regenerate it from current artwork.')
  print('PASS current art hashes, all 19 bird poses and pickup masks')
 else:OUT.write_text(content);print('Wrote',OUT)
